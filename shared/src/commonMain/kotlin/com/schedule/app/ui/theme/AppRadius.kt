package com.schedule.app.ui.theme

import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.ui.unit.dp

// ─── Единый источник правды для скруглений ────────────────────────────────────
//
//  Раньше в проекте было ~10 разных значений (8/10/12/13/14/16/19/20/23/24/26/
//  30/34dp) вперемешку с CircleShape — визуально "скругление пилюли" (нижняя
//  навигация, полностью круглая) не сочеталось со скруглением карточек и
//  переключателей, у каждого из которых было своё случайное число.
//
//  Теперь два токена вместо десятка чисел:
//   - card    — обычные прямоугольные карточки (файлы, пары, звонки, блоки
//               настроек). Единое число, а не "почти похожие" 14/16dp.
//   - capsule — любой элемент, который по смыслу должен быть ПОЛНОСТЬЮ круглым
//               по высоте (переключатели, тумблер, кнопка, бейджи, тост) —
//               через RoundedCornerShape(percent = 50) вместо подбора dp
//               "на глаз", близкого к половине высоты. Percent-форма сама
//               подстраивается под фактическую высоту компонента и всегда даёт
//               настоящую капсулу — тот же язык, что и у круглой нижней
//               навигации, а не число, которое лишь примерно похоже на неё.
object AppRadius {
    val card = RoundedCornerShape(16.dp)
    val capsule = RoundedCornerShape(percent = 50)
}
